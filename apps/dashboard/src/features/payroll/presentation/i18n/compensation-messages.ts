export const compensationMessages = (locale: Locale) => (locale === "id" ? indonesian : english);
export function compensationFieldError(
  failure: Failure | null,
  field: string,
  locale: Locale,
): string | undefined {
  const code =
    failure?.fields[field] ??
    Object.entries(failure?.fields ?? {}).find(([key]) => key.startsWith(`${field}[`))?.[1];
  if (!code) return undefined;
  if (code === "required") return locale === "id" ? "Isi nilai ini." : "This value is required.";
  if (code === "duplicate")
    return locale === "id"
      ? "Gunakan kode tunjangan yang berbeda."
      : "Use a distinct code for each earning.";
  if (code === "too_many")
    return locale === "id" ? "Maksimal 20 tunjangan tetap." : "Use up to 20 fixed earnings.";
  if (
    code === "out_of_range" &&
    (field.endsWith("Salary") ||
      field.endsWith("Wage") ||
      field.endsWith("amount") ||
      field.endsWith("Contribution") ||
      field.endsWith("Donation") ||
      field.endsWith("Deduction"))
  )
    return locale === "id"
      ? "Periksa nominal: maksimal IDR 50.000.000.000 dengan dua angka desimal. Gaji pokok dan upah dasar iuran harus di atas nol."
      : "Check the amount: up to IDR 50,000,000,000 with two decimal places. Basic salary and contribution wage must be above zero.";
  return locale === "id" ? "Periksa nilai ini." : "Check this value.";
}
