export const payrollInputMessages = (locale: Locale) => (locale === "id" ? id : en);
export function payrollInputFieldError(
  failure: Failure | null,
  field: string,
  locale: Locale,
): string | undefined {
  const code = failure?.fields[field];
  if (!code) return undefined;
  if (code === "required") return locale === "id" ? "Isi nilai ini." : "This value is required.";
  if (code === "duplicate")
    return locale === "id"
      ? "Gunakan kode yang berbeda untuk setiap baris."
      : "Use a distinct code for each line.";
  if (code === "overlap")
    return locale === "id"
      ? "Bagian hari tidak boleh tumpang tindih."
      : "Day portions must not overlap.";
  if (code === "outside_period")
    return locale === "id"
      ? "Pilih tanggal dalam bulan penghasilan."
      : "Select a date in the earnings month.";
  if (code === "positive_required")
    return locale === "id" ? "Masukkan nominal di atas nol." : "Enter an amount above zero.";
  return locale === "id" ? "Periksa nilai ini." : "Check this value.";
}
