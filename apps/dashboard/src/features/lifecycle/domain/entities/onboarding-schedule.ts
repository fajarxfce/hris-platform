import type { AccountId, CompanyId } from "../../../../core/domain/identifiers";
import type { EmployeeId } from "../../../people/domain/entities/employee";
import type { LifecycleCaseId } from "./lifecycle-case";
import type { LifecycleScheduleJob } from "./lifecycle-schedule-job";
import type { LifecycleTemplate } from "./lifecycle-template";
export type OnboardingScheduleId = string & { readonly onboardingScheduleId: unique symbol };
export type OnboardingScheduleAction = "cancel" | "recover";
export type OnboardingSchedule = Readonly<{
  id: OnboardingScheduleId;
  companyId: CompanyId;
  caseId: LifecycleCaseId;
  employmentId: EmployeeId;
  status: "SCHEDULED" | "STARTED" | "FAILED" | "CANCELLED";
  version: number;
  employmentVersion: number;
  appliedEmploymentRevision: number;
  template: LifecycleTemplate;
  assignees: Readonly<Record<string, AccountId>>;
  targetDate: string;
  startsOn: string;
  companyTimezone: string;
  scheduledFor: string;
  validUntil: string;
  attempt: number;
  createdBy: AccountId;
  createdAt: string;
  reason: string;
  finishedAt: string | null;
  failureCode: string | null;
  job: LifecycleScheduleJob;
  actions: readonly OnboardingScheduleAction[];
}>;
