export const taxOpeningMessages = (locale: Locale) => (locale === "id" ? id : en);
export function taxOpeningFieldError(
  failure: Failure | null,
  field: string,
  locale: Locale,
): string | undefined {
  const code = failure?.fields[field];
  if (!code) return undefined;
  if (code === "required") return locale === "id" ? "Isi nilai ini." : "This value is required.";
  if (code === "inconsistent")
    return locale === "id"
      ? "Periksa kesesuaian total penghasilan, pengurangan, dan jumlah bulan bekerja."
      : "Check the income, deductions and employment-month totals.";
  if (code === "no_previous_month")
    return locale === "id"
      ? "Gunakan total nihil jika tidak ada bulan sebelumnya."
      : "Use zero totals when there is no earlier month.";
  if (code === "non_resident_reconciliation_not_applicable")
    return locale === "id"
      ? "Riwayat pemberi kerja sebelumnya tidak berlaku untuk subjek pajak luar negeri."
      : "Previous employer reconciliation does not apply to non-residents.";
  return locale === "id" ? "Periksa nilai ini." : "Check this value.";
}
