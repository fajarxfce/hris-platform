export const expenseDraftMessages = (locale: Locale) => (locale === "id" ? id : en);
export function expenseDraftFieldError(
  code: string | undefined,
  locale: Locale,
): string | undefined {
  if (!code) return undefined;
  const text = expenseDraftMessages(locale);
  return text[code as keyof typeof text] ?? text.invalid_value;
}
